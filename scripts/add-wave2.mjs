let id = Math.max(...data.map((m) => m.id))
const usedSlugs = new Set(data.map((m) => m.slug))
const added = []
for (const e of ENTRIES) {
  const g = geo[e.geoKey]
  if (!g) { console.log('ПРОПУСК (нет координат):', e.title); continue }
  let slug = slugify(e.title)
  if (usedSlugs.has(slug)) slug += '-2'
  id += 1
  usedSlugs.add(slug)
  added.push({
    id, slug,
    title: e.title, city: e.city, region: e.region,
    year: null, category: e.category, image: '',
    shortDescription: e.short, fullHistory: e.full,
    coordinates: { lat: g.lat, lng: g.lng },
    facts: e.facts,
    likes: 0, images: [],
    factsSource: { label: e.src[0], url: e.src[1] }
  })
  console.log(`+#${id} ${e.title} — ${e.city}`)
}

fs.writeFileSync(p, `export const monuments = ${JSON.stringify([...data, ...added], null, 2)}\n`, 'utf8')
console.log(`добавлено: ${added.length}, всего: ${data.length + added.length}`)
