// Сопоставление субъектов с написанием в каталоге (грубое): точное совпадение
// или вхождение нормализованного ствола.
function regionInCatalog(subject) {
  const s = norm(subject)
  for (const r of byRegion.keys()) {
    const rN = norm(r)
    if (rN === s || rN.includes(s) || s.includes(rN.split(' ')[0])) return { region: r, count: byRegion.get(r).length }
  }
  return null
}

console.log('=== Покрытие субъектов сейчас:')
const noCoverage = []
const lowCoverage = []
for (const [group, subjects] of Object.entries(GROUPS)) {
  for (const subj of subjects) {
    const hit = regionInCatalog(subj)
    if (!hit) { noCoverage.push(subj); console.log(`  [  0] ${subj} (${group})`) }
    else if (hit.count <= 3) { lowCoverage.push(subj) }
  }
}
console.log(`\nПолностью без покрытия: ${noCoverage.length}, с 1-3 записями: ${lowCoverage.length}`)
console.log('Регионы каталога:', [...byRegion.keys()].length, '| записей:', monuments.length)

// Чанки: смешиваем пустые/малые регионы по округам, 5-7 субъектов на агента
const chunkPlan = []
const flat = Object.entries(GROUPS).flatMap(([group, subjects]) =>
  subjects.map((s) => {
    const hit = regionInCatalog(s)
    return { subject: s, group, count: hit ? hit.count : 0, existing: hit ? byRegion.get(hit.region) : [] }
  })
)
// приоритет: сначала регионы без покрытия, затем малые, затем остальные — но держим округа вместе
flat.sort((a, b) => a.group.localeCompare(b.group) || a.count - b.count)
const CHUNK = 6
for (let i = 0; i < flat.length; i += CHUNK) {
  chunkPlan.push(flat.slice(i, i + CHUNK))
}
fs.mkdirSync('scripts/enrich', { recursive: true })
chunkPlan.forEach((chunk, i) => {
  fs.writeFileSync(`scripts/enrich/hunt-${i + 1}.json`, JSON.stringify(chunk.map((c) => ({
    region: c.subject,
    inCatalogNow: c.count,
    existingTitles: c.existing
  })), null, 2), 'utf8')
})
console.log(`\nЧанков охоты: ${chunkPlan.length} (hunt-1..${chunkPlan.length}.json)`)
